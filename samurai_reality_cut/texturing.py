def _save_img(name, arr, path, srgb, quality):
    h, w = arr.shape[:2]
    from PIL import Image
    im = Image.fromarray((np.clip(arr, 0, 1) * 255 + 0.5).astype(np.uint8))
    im.save(path, quality=quality, subsampling=0) if path.endswith('.jpg') else im.save(path, optimize=True)
    img = bpy.data.images.load(path, check_existing=False)
    img.name = name
    img.colorspace_settings.name = 'sRGB' if srgb else 'Non-Color'
    img.pack()
    return img


def make_material(name, alb_img, orm_img, nrm_img):
    m = bpy.data.materials.new(name); m.use_nodes = True
    nt = m.node_tree; nt.nodes.clear()
    out = nt.nodes.new('ShaderNodeOutputMaterial'); out.location = (800, 0)
    bsdf = nt.nodes.new('ShaderNodeBsdfPrincipled'); bsdf.location = (500, 0)
    nt.links.new(bsdf.outputs['BSDF'], out.inputs['Surface'])
    a = nt.nodes.new('ShaderNodeTexImage'); a.image = alb_img; a.location = (-400, 300); a.label = 'BaseColor'
    nt.links.new(a.outputs['Color'], bsdf.inputs['Base Color'])
    o = nt.nodes.new('ShaderNodeTexImage'); o.image = orm_img; o.location = (-700, 0); o.label = 'ORM'
    sep = nt.nodes.new('ShaderNodeSeparateColor'); sep.location = (-420, 0)
    nt.links.new(o.outputs['Color'], sep.inputs['Color'])
    nt.links.new(sep.outputs['Green'], bsdf.inputs['Roughness'])
    nt.links.new(sep.outputs['Blue'], bsdf.inputs['Metallic'])
    n = nt.nodes.new('ShaderNodeTexImage'); n.image = nrm_img; n.location = (-700, -300); n.label = 'Normal'
    nm = nt.nodes.new('ShaderNodeNormalMap'); nm.location = (-200, -300); nm.inputs['Strength'].default_value = 1.0
    nt.links.new(n.outputs['Color'], nm.inputs['Color'])
    nt.links.new(nm.outputs['Normal'], bsdf.inputs['Normal'])
    return m


def texture_scene(arm, out_dir, scale=1.0, quality=90, only=None):
    os.makedirs(out_dir, exist_ok=True)
    report = {}
    for on, (kind, fn, size) in PAINTERS.items():
        if only and on not in only: continue
        obj = bpy.data.objects.get(on)
        if obj is None or obj.type != 'MESH': continue
        if not obj.data.uv_layers:
            bpy.context.view_layer.objects.active = obj
            obj.select_set(True)
            bpy.ops.object.mode_set(mode='EDIT'); bpy.ops.mesh.select_all(action='SELECT')
            bpy.ops.uv.smart_project(angle_limit=math.radians(66), island_margin=0.01)
            bpy.ops.object.mode_set(mode='OBJECT')
        size = int(size * scale)
        rid, rf = _region_fn(obj, kind)
        set_bone_table(arm)
        bf = _bone_fn(obj)
        R = rasterize(obj, arm, size, rf, bf)
        m = fn(R, rid)
        alb = m['alb']; rough = m['rough']; metal = m['metal']; height = m['height']; ao = m['ao']
        orm = np.stack([ao, rough, metal], -1)
        nrm = height_to_normal(height.astype(np.float32), strength=float(max(1.0, size / 512.0)))
        alb = dilate(alb, R.mask); orm = dilate(orm, R.mask); nrm = dilate(nrm, R.mask)
        alb = np.where(R.mask[..., None], alb, np.array([0.1, 0.1, 0.1], np.float32))
        aimg = _save_img(f'{on}_albedo', alb, os.path.join(out_dir, f'{on}_albedo.jpg'), True, quality)
        oimg = _save_img(f'{on}_orm', orm, os.path.join(out_dir, f'{on}_orm.jpg'), False, quality)
        nimg = _save_img(f'{on}_normal', nrm, os.path.join(out_dir, f'{on}_normal.jpg'), False, 95)
        mat = make_material(f'tex_{on}', aimg, oimg, nimg)
        obj.data.materials.clear(); obj.data.materials.append(mat)
        for p in obj.data.polygons: p.material_index = 0
        report[on] = size
        print('textured', on, size, flush=True)
    return report
