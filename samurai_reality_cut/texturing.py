def _groups_for(obj):
    vg = {i: g.name for i, g in enumerate(obj.vertex_groups)}
    return vg


def _bone_fn(obj):
    me = obj.data; vg = {i: g.name for i, g in enumerate(obj.vertex_groups)}
    idx = {n: i for i, n in enumerate(_BT['names'])}
    out = np.full(len(me.polygons), -1, np.int16)
    for p in me.polygons:
        w = {}
        for vi in p.vertices:
            for g in me.vertices[vi].groups:
                n = vg.get(g.group)
                if n in idx: w[n] = w.get(n, 0) + g.weight
        if w: out[p.index] = idx[max(w, key=w.get)]
    return lambda i: out[i]


def _region_fn(obj, kind):
    me = obj.data; vg = _groups_for(obj)
    rid = {}
    out = np.zeros(len(me.polygons), np.int16)
    if kind in ('armo', 'prot', 'neiyi'):
        rid = {'body': 1, 'rope': 2, 'leg': 3, 'other': 0}
        for p in me.polygons:
            w = {}
            for vi in p.vertices:
                for g in me.vertices[vi].groups:
                    n = vg.get(g.group, '')
                    c = 'rope' if n.startswith('rope') else ('leg' if n.endswith(('leg', 'knee', 'ankle', 'foot', 'foottop')) else ('body' if n in ('HIP', 'spine', 'chest', 'neck') else 'other'))
                    w[c] = w.get(c, 0) + g.weight
            out[p.index] = rid[max(w, key=w.get)] if w else 0
    elif kind == 'sword':
        rid = {'steel': 0, 'tsuba': 1, 'gold': 2, 'wrap': 3, 'lacquer': 4}
        for p in me.polygons: out[p.index] = p.material_index
    else:
        rid = {}
    return rid, (lambda i: out[i])


